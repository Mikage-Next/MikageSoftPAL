//! agree); handlers that pop through a helper of their own (11:2), take a
//! variable count (15:4, 18:9) or run again while waiting (7:3) are reported
//! wrongly.

pub(crate) fn audit_enabled() -> bool {
    static ENABLED: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *ENABLED.get_or_init(|| std::env::var_os("SENA_ARITY_AUDIT").is_some())
}

